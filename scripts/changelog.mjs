#!/usr/bin/env node
/**
 * 版本与更新日志（没有手写的版本号）：
 *
 *   node scripts/changelog.mjs --write   由 conventional commits 生成 CHANGELOG.md 中缺少的版本段落（已有段落冻结），
 *                                        并重写 README 里 <!-- versions:start --> … <!-- versions:end --> 之间的版本徽章
 *   node scripts/changelog.mjs --check   CI：三个 package.json、package-lock、CHANGELOG 顶部版本、release-meta、README 徽章必须一致
 *
 * 版本来源：根 package.json 的 version；依赖版本（Motionary 等）来自 package-lock.json 实际解析的版本。
 * 里程碑映射：Lnn = 1.nn.0（见 scripts/release-meta.json）。
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const REPO = 'https://github.com/HarrisonCN/TheBLOG';

export const TYPES = [
  ['feat', '新功能 Features'],
  ['fix', '修复 Fixes'],
  ['perf', '性能 Performance'],
  ['refactor', '重构 Refactoring'],
  ['test', '测试 Tests'],
  ['docs', '文档 Docs'],
  ['build', '构建 Build'],
  ['ci', 'CI'],
  ['chore', '杂项 Chores'],
  ['other', '其他 Other'],
];

/** 解析一条提交标题：type(scope)!: subject */
export function parseCommit(subject) {
  const m = /^(\w+)(?:\(([^)]+)\))?(!)?:\s*(.+)$/.exec(subject.trim());
  if (!m) return { type: 'other', scope: null, breaking: false, subject: subject.trim() };
  const type = m[1].toLowerCase();
  if (type === 'other' || !TYPES.some(([t]) => t === type)) return { type: 'other', scope: null, breaking: false, subject: subject.trim() };
  return { type, scope: m[2] ?? null, breaking: !!m[3], subject: m[4] };
}

/** 一个版本的段落（Markdown） */
export function renderSection({ version, date, title, commits }) {
  const groups = new Map();
  for (const c of commits) {
    const p = parseCommit(c.subject);
    if (/^(wip|squash!|fixup!|docs\(changelog\)(!)?:\s*regenerate)/i.test(c.subject)) continue;
    if (!groups.has(p.type)) groups.set(p.type, []);
    groups.get(p.type).push({ ...p, sha: c.sha });
  }
  const lines = [`## [${version}](${REPO}/releases/tag/v${version})${date ? ` — ${date}` : ''}`, ''];
  if (title) lines.push(`_${title}_`, '');
  for (const [t, label] of TYPES) {
    const g = groups.get(t);
    if (!g?.length) continue;
    lines.push(`### ${label}`, '');
    for (const c of g) lines.push(`- ${c.breaking ? '**BREAKING** ' : ''}${c.scope ? `**${c.scope}:** ` : ''}${c.subject} (${c.sha.slice(0, 7)})`);
    lines.push('');
  }
  return lines.join('\n');
}

function gitLog(range) {
  try {
    const out = execFileSync('git', ['log', '--no-merges', '--format=%H%x09%s', range], { cwd: root, encoding: 'utf8' });
    return out.split('\n').filter(Boolean).map((l) => ({ sha: l.split('\t')[0], subject: l.split('\t').slice(1).join('\t') }));
  } catch {
    return [];
  }
}
function gitDate(rev) {
  try {
    return execFileSync('git', ['log', '-1', '--format=%cs', rev], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

/** 各处的版本号 */
export function collectVersions() {
  const rootPkg = readJson('package.json');
  const web = readJson('web/package.json');
  const worker = readJson('worker/package.json');
  const lock = readJson('package-lock.json');
  return {
    root: rootPkg.version,
    web: web.version,
    worker: worker.version,
    lockRoot: lock.version,
    lockRootPkg: lock.packages?.['']?.version,
    lockWeb: lock.packages?.web?.version,
    lockWorker: lock.packages?.worker?.version,
    motionary: lock.packages?.['node_modules/motionary']?.version,
    motionaryRange: web.dependencies?.motionary,
    node: rootPkg.engines?.node,
  };
}

/** README 版本徽章块（由 package.json / package-lock 生成） */
export function badgeBlock(v) {
  const b = (label, msg, color, link) => `[![${label}](https://img.shields.io/badge/${encodeURIComponent(label).replace(/-/g, '--')}-${encodeURIComponent(msg).replace(/-/g, '--')}-${color})](${link})`;
  return [
    '<!-- versions:start (generated by scripts/changelog.mjs --write; do not edit) -->',
    `${b('version', v.root, '2563eb', `${REPO}/releases/tag/v${v.root}`)} ${b('motionary', v.motionary, '7c3aed', `https://www.npmjs.com/package/motionary/v/${v.motionary}`)} ${b('node', v.node, '16a34a', 'https://nodejs.org/')}`,
    '',
    `当前版本 **${v.root}** · Motionary **${v.motionary}** · Node **${v.node}** — 里程碑映射 Lnn = 1.nn.0，见 [CHANGELOG.md](CHANGELOG.md)。`,
    '<!-- versions:end -->',
  ].join('\n');
}
const BADGE_RE = /<!-- versions:start[^>]*-->[\s\S]*?<!-- versions:end -->/;

export function topChangelogVersion(md) {
  return /^## \[(\d+\.\d+\.\d+)\]/m.exec(md)?.[1] ?? null;
}

export function check() {
  const v = collectVersions();
  const meta = readJson('scripts/release-meta.json');
  const problems = [];
  for (const [k, val] of Object.entries({ web: v.web, worker: v.worker, lockRoot: v.lockRoot, lockRootPkg: v.lockRootPkg, lockWeb: v.lockWeb, lockWorker: v.lockWorker })) {
    if (val !== v.root) problems.push(`${k} 版本 ${val} ≠ 根 package.json ${v.root}`);
  }
  if (!/^\d+\.\d+\.\d+$/.test(v.root)) problems.push(`根版本 ${v.root} 不是 SemVer`);
  if (meta.releases[0]?.version !== v.root) problems.push(`release-meta.json 最新版本 ${meta.releases[0]?.version} ≠ ${v.root}`);
  const cl = existsSync(join(root, 'CHANGELOG.md')) ? readFileSync(join(root, 'CHANGELOG.md'), 'utf8') : '';
  if (topChangelogVersion(cl) !== v.root) problems.push(`CHANGELOG.md 顶部版本 ${topChangelogVersion(cl)} ≠ ${v.root}（运行 node scripts/changelog.mjs --write）`);
  for (const r of meta.releases) if (!cl.includes(`## [${r.version}]`)) problems.push(`CHANGELOG.md 缺少 ${r.version}`);
  const readme = readFileSync(join(root, 'README.md'), 'utf8');
  const block = BADGE_RE.exec(readme)?.[0];
  if (block !== badgeBlock(v)) problems.push('README 版本徽章与 package.json / package-lock 不一致（运行 node scripts/changelog.mjs --write）');
  // README 正文里不允许手写 Motionary 版本号（只能出现在生成的徽章块里）
  const body = readme.replace(BADGE_RE, '');
  const typed = body.match(/motionary[@\s（(]*\d+\.\d+(\.\d+)?/gi);
  if (typed) problems.push(`README 正文里有手写的 Motionary 版本：${typed.join(', ')}`);
  return problems;
}

export function write() {
  const v = collectVersions();
  const meta = readJson('scripts/release-meta.json');
  const path = join(root, 'CHANGELOG.md');
  const existing = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const sections = [];
  for (const r of meta.releases) {
    const frozen = new RegExp(`^## \\[${r.version.replace(/\./g, '\\.')}\\][\\s\\S]*?(?=^## \\[|^## 历史|(?![\\s\\S]))`, 'm').exec(existing)?.[0];
    // 已发布（release-meta 里有 sha）的段落冻结；当前未发布版本每次从 from..HEAD 重新生成
    if (frozen && r.sha) {
      sections.push(frozen.trimEnd() + '\n');
      continue;
    }
    const range = r.sha ? `${r.from}..${r.sha}` : `${r.from}..HEAD`;
    sections.push(renderSection({ version: r.version, date: r.date ?? (r.sha ? gitDate(r.sha) : ''), title: `${r.milestone} · ${r.title}`, commits: gitLog(range) }));
  }
  const history = ['## 历史（SemVer 之前的里程碑）', '', '1.14.0 之前的里程碑没有单独打版本号；按合并顺序记录如下。', '', ...meta.history.map((h) => `- ${h.date} · ${h.title}${h.pr ? ` ([#${h.pr}](${REPO}/pull/${h.pr}))` : ''} (${h.sha})`), ''];
  const md = ['# 更新日志 · Changelog', '', '本文件由 `node scripts/changelog.mjs --write` 从 conventional commits 生成（已发布版本的段落冻结）。版本遵循 SemVer，里程碑映射 **Lnn = 1.nn.0**。', '', ...sections, ...history].join('\n');
  writeFileSync(path, md);
  const readmePath = join(root, 'README.md');
  const readme = readFileSync(readmePath, 'utf8');
  const block = badgeBlock(v);
  writeFileSync(readmePath, BADGE_RE.test(readme) ? readme.replace(BADGE_RE, block) : readme.replace(/^(# .+\n)/, `$1\n${block}\n`));
  return md;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--write')) {
    write();
    console.log('[changelog] CHANGELOG.md + README 版本徽章已生成');
  }
  if (process.argv.includes('--check') || !process.argv.includes('--write')) {
    const problems = check();
    if (problems.length) {
      console.error(`[changelog] ✖ 版本不一致：\n  - ${problems.join('\n  - ')}`);
      process.exit(1);
    }
    console.log(`[changelog] ✓ 版本一致：${collectVersions().root}`);
  }
}
